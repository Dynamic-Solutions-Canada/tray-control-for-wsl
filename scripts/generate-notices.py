#!/usr/bin/env python3
"""Generate WslMonitor/THIRD-PARTY-NOTICES.txt from the app's NuGet restore graph (HYG-3, D-085).

    python3 scripts/generate-notices.py          write the file
    python3 scripts/generate-notices.py --check  fail if the committed file is out of date, or if the
                                                 About page's notices link names another path (validate)

Reads WslMonitor/obj/project.assets.json, which any restore writes (`npm run format:check` restores
the project first in `validate`), and each package's .nuspec and licence files from the NuGet package
cache ($NUGET_PACKAGES, default ~/.nuget/packages). Every package in the graph is listed except
build-time tooling (names containing "BuildTools"), which never ships in the MSIX.

Licences are written out in full: a package's own licence file when it has one, otherwise the standard
text for its SPDX expression. An expression the script has no text for fails the run, so a new
dependency is never shipped without its licence. Identical texts are printed once and referenced.
The .NET runtime that ships inside the self-contained package is listed with a link to its notices.

Standard library only.
"""
